/* shots-ui.jsx — The Art Room ▸ Shot List (React).
   Scene-grouped shot list. Each shot is ONE beat, carrying cinematographer grammar
   (size · angle · movement · lens), the subjects/location/props in frame, an action
   line and an editable composition note. The frame is generated by composing the
   scene's Style Bible grade + the location plate + the character/prop sheets as
   reference images (see buildShotPrompt). Reuses SheetFrame, useImageGen and the
   shared batch engine so it behaves exactly like the other Art Room tabs. */

const _el = React.createElement;

function shotCardReferenceLabel(sh, sceneShots){
  const beatShots=(sceneShots||[]).filter(s=>Number(s.beatN)===Number(sh&&sh.beatN));
  if(typeof shotBeatDisplayLabel==="function")
    return shotBeatDisplayLabel(sh,beatShots).replace(/ · Opening$/,"");
  return sh&&Number(sh.beatN)>0 ? "Beat "+Number(sh.beatN) : "Unnumbered shot";
}

/* is this card the one a run's step belongs to? Its own frame, or its beat's end frame (2026-11-22) */
function shotRunsHere(sh, activeId){
  return !!(sh && activeId) && (sh.id===activeId || (typeof shotEndFrameId==="function" && shotEndFrameId(sh.id)===activeId));
}

/* a labelled grammar dropdown (size / angle / move / lens) */
function GrammarSelect({ label, value, options, onChange }){
  // a value outside the list (a lens set to any mm in the Blender preview) shows as itself (2026-10-05)
  const extra = (value!=null && value!=="" && !options.some(o=>o.id===value)) && /^\d{1,3}$/.test(String(value))
    ? { id:String(value), label:String(value)+"mm", desc:"set in the Blender preview" } : null;
  return _el("label",{className:"shot-gsel"},
    _el("span",{className:"shot-gsel-lab"},label),
    _el("select",{className:"prop-select",value:value,onChange:e=>onChange(e.target.value)},
      (extra ? [extra, ...options] : options).map(o=>_el("option",{key:o.id,value:o.id,title:o.desc||""},o.label))));
}

function CameraFieldLabel({ label, auto }){
  return _el("span",{className:"shot-gsel-head"},
    _el("span",{className:"shot-gsel-lab"},label),
    auto && _el("span",{
      className:"shot-camera-auto",
      title:"Auto — showing the value inferred from the shot; no camera override set",
      "aria-label":"Auto, inferred value with no explicit camera override"
    },"Auto"));
}

function CameraSettingSelect({ label, value, options, onChange, effective }){
  const isAuto = !value || value==="auto";
  const displayOptions = (options||[]).map(o=>{
    if(o.id==="auto" && isAuto && effective) return { ...o, label:effective };
    return o;
  });
  return _el("label",{className:"shot-gsel"+(isAuto?" recommended":"")},
    _el(CameraFieldLabel,{label,auto:isAuto}),
    _el("select",{className:"prop-select",value:value||"auto",onChange:e=>onChange(e.target.value),
      "aria-label":isAuto ? label+" — automatic recommendation: "+(effective||"Auto") : label},
      displayOptions.map(o=>_el("option",{key:o.id,value:o.id,title:o.desc||""},o.label))));
}

function CameraProfilePicker({ value, options, onChange, recommendedLabel }){
  const [open, setOpen] = React.useState(false);
  const [expanded, setExpanded] = React.useState({});
  const [pos, setPos] = React.useState(null);
  const triggerRef = React.useRef(null), menuRef = React.useRef(null);
  const list = options || [];
  const cur = list.find(o=>o.id===(value||"auto")) || list[0] || { id:"auto", label:"Project default / None", family:"Camera" };
  const isAuto = !value || value==="auto";
  const triggerLabel = isAuto ? (recommendedLabel || cur.label || "Project default / None") : cur.label;
  const place = ()=>{ const t=triggerRef.current; if(!t) return; const r=t.getBoundingClientRect(); setPos({ top:r.bottom+4, left:r.left, width:r.width }); };
  React.useEffect(()=>{
    if(!open) return;
    const onDoc=(e)=>{ if((menuRef.current&&menuRef.current.contains(e.target))||(triggerRef.current&&triggerRef.current.contains(e.target))) return; setOpen(false); };
    const onKey=(e)=>{ if(e.key==="Escape") setOpen(false); };
    const reflow=(e)=>{ if(menuRef.current && e && e.target && menuRef.current.contains(e.target)) return; place(); };
    document.addEventListener("mousedown",onDoc); document.addEventListener("keydown",onKey);
    window.addEventListener("scroll",reflow,true); window.addEventListener("resize",reflow);
    return ()=>{ document.removeEventListener("mousedown",onDoc); document.removeEventListener("keydown",onKey); window.removeEventListener("scroll",reflow,true); window.removeEventListener("resize",reflow); };
  },[open]);
  React.useEffect(()=>{ if(open) setExpanded(prev=>Object.keys(prev).length?{...prev,[cur.family||"Other cameras"]:true}:{[cur.family||"Other cameras"]:true}); },[open, cur.family]);
  const groups = [], byGroup = {};
  list.forEach(o=>{ const g=o.family||"Other cameras"; if(!byGroup[g]){ byGroup[g]=[]; groups.push(g); } byGroup[g].push(o); });
  const pick = (id)=>{ setOpen(false); onChange && onChange(id); };
  const toggleGroup = (e,g)=>{ e.stopPropagation(); setExpanded(prev=>prev[g]?{}:{[g]:true}); };
  const menu = (open && pos && window.ReactDOM && window.ReactDOM.createPortal) ? window.ReactDOM.createPortal(
    _el("div",{className:"rs-menu camera-profile-menu",ref:menuRef,style:{position:"fixed",top:pos.top+"px",left:pos.left+"px",minWidth:pos.width+"px"}},
      groups.map(g=>{
        const rows = byGroup[g] || [];
        const isOpen = !!expanded[g];
        const selectedInGroup = rows.some(o=>o.id===(value||"auto"));
        return _el("div",{key:g,className:"rs-group"+(isOpen?" open":"")+(selectedInGroup?" has-sel":"")},
          _el("button",{type:"button",className:"rs-group-head",onClick:(e)=>toggleGroup(e,g),title:(isOpen?"Collapse ":"Expand ")+g},
            _el("span",{className:"rs-group-caret"},isOpen?"▾":"▸"),
          _el("span",{className:"rs-group-lab"},g),
          _el("span",{className:"rs-group-count"},rows.length)),
          isOpen && _el("div",{className:"rs-group-body"},
            rows.map(o=>_el("div",{key:o.id,className:"rs-opt"+(o.id===(value||"auto")?" sel":""),title:o.desc||o.label,onClick:()=>pick(o.id)},
              _el("span",{className:"rs-opt-lab"},o.label)))));
      })), document.body) : null;
  return _el("div",{className:"rs-picker camera-profile-picker"+(open?" open":"")},
    _el("button",{type:"button",className:"rs-trigger",ref:triggerRef,
      "aria-label":isAuto ? "Camera profile — automatic recommendation: "+triggerLabel : "Camera profile: "+triggerLabel,
      onClick:()=>{ if(open) setOpen(false); else { place(); setOpen(true); } }},
      _el("span",{className:"rs-trigger-lab"},triggerLabel),
      _el("span",{className:"rs-caret"},"▾")),
    menu);
}

/* POINT OF VIEW (2026-10-28, scale plan step 2): whose eyes this shot sees through — the camera's height, optics and
   how big everything looks follow that character's true size. Shown only in a film whose cast isn't all human-sized;
   Automatic = the smallest character in frame when the frame isn't all human-sized. */
function ShotPovPicker({ sh, characters, onUpdate }){
  const cast = (characters||[]).filter(c=>c && c.id && c.name);
  const mixed = typeof scaleClassOf==="function" && cast.some(c=>scaleClassOf(c)!=="A");
  if(!mixed) return null;
  const sizeOf = (c)=> (typeof heightMMOf==="function" && heightMMOf(c)>0 && typeof scaleMeasurementOf==="function") ? " ("+scaleMeasurementOf(c)+")" : "";
  return _el("label",{className:"shot-gsel shot-pov-pick","data-testid":"shot-pov-pick",
      title:"Whose eyes this shot sees through: the camera's height, lens and how big everything looks follow that character's size"},
    _el("span",{className:"shot-gsel-lab"},"Point of view"),
    _el("select",{className:"prop-select",value:sh.povCharacterId||"",onChange:e=>onUpdate(sh.id,{ povCharacterId:e.target.value||"" })},
      _el("option",{value:""},"Automatic \u2014 the smallest in frame"),
      cast.map(c=>_el("option",{key:c.id,value:c.id},c.name+sizeOf(c)))));
}
