  // only stands in until the scene is drafted
  const beatText = beatScriptText(scene.id, L.n)
    || (beatRow ? [ (beatRow.drive&&beatRow.drive.d||"").trim(), (beatRow.react&&beatRow.react.d||"").trim() ].filter(Boolean).join(" \u2014 ") : "");
