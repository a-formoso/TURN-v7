/* test-rebrand-art.mjs — Kinolot rebrand guard for the Art Room & Stage surfaces
   (owner decisions 2026-09-28).

   What it pins:
   A. No user-visible string in these files says the internal codename "TURN", the old
      product name "Cinema Machine", the assistant's old name "MUSE", an old agent
      name (Consistency Check / Continuity Repair / Art Department Coordinator), the
      curly-apostrophe "Writers’ Room", the plan name "Studio" or "Generated by …".
      Only string literals, template text and JSX text are checked — comments,
      identifiers, storage keys and regexes are internal and may keep the codename.
   B. New images record the render-prompt compiler as "Kinolot prompt compiler".
   C. Images that already saved "TURN prompt compiler" DISPLAY the product name
      (stored metadata is never rewritten) — promptCompilerLabel() is executed.
   D. The Stage film export is named after the film ("The_Matrix-2026-09-28.webm"),
      else "Kinolot-film-2026-09-28.webm" — stageFilmFileName() is executed.
   E. The top plan is SHOWN as "Producer" in the Stage (display only).
   F. Export footers say "Made with Kinolot"; "Suggested from the script" chips.

   Run: node scripts/test-rebrand-art.mjs  (no browser, no network) */
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(ROOT, "package.json"));
const babel = require("@babel/core");

let pass = 0, fail = 0;
function ok(name, cond, extra){
  if(cond){ pass++; console.log("PASS", name); }
  else { fail++; console.log("FAIL", name, extra!==undefined ? JSON.stringify(extra).slice(0,600) : ""); }
}
const read = (f)=>readFileSync(join(ROOT, f), "utf8");
function parse(f, src){
  return babel.parseSync(src, { filename:f, babelrc:false, configFile:false, sourceType:"script",
    presets:[require.resolve("@babel/preset-react")] });
}

/* Builder 4's files: the Art Room & Stage surfaces, plus the three unowned files
   that carried a user-visible name (character-identity-ui, locations, stage-screenplay-ui). */
const FILES = [
  "app/artroom.jsx", "app/lookbook.jsx", "app/stage.jsx", "app/imagegen.jsx", "app/stylebible-ui.jsx",
  "app/breakdown.jsx", "app/shots-ui.jsx", "app/props.jsx", "app/locations-ui.jsx", "app/videogen.jsx",
  "app/voicegen.jsx", "app/voices-ui.jsx", "app/cameo.jsx", "app/art-tab-locks.js", "app/cast-policy.js",
  "app/character-identity-ui.jsx", "app/locations.jsx", "app/stage-screenplay-ui.jsx",
];
const BANNED = [
  ["the internal codename TURN", /\bTURN\b/],
  ["the old product name", /Cinema ?Machine/i],
  ["the assistant's old name", /\bMUSE\b/],
  ["an old agent name", /Consistency Check|Continuity Repair|Art Department Coordinator/],
  ["a curly or missing Writers' Room apostrophe", /Writers’ Room|Writers Room\b|Writer's Room/],
  ["the plan name Studio", /\bStudio plan\b/],
  ["a 'Generated by' credit", /Generated by (?:Cinema|TURN|Kinolot)/],
];

/* ── A. user-visible strings ─────────────────────────────────────────────── */
const asts = {};
for(const f of FILES){
  const src = read(f);
  let ast = null;
  try{ ast = parse(f, src); }catch(e){ ok("A "+f+" parses", false, e.message); continue; }
  asts[f] = { src, ast };
  const hits = [];
  babel.traverse(ast, { enter(p){
    const n = p.node; let t = null;
    if(n.type==="StringLiteral") t = n.value;
    else if(n.type==="TemplateElement") t = n.value.cooked;
    else if(n.type==="JSXText") t = n.value;
    if(t==null) return;
    for(const [what, re] of BANNED) if(re.test(t)) hits.push(f+":"+n.loc.start.line+" "+what+": "+t.slice(0,120));
  }});
  ok("A "+f+" shows no old or internal names", hits.length===0, hits);
}

/* helper: pull one top-level function's source out of a file and run it in a sandbox */
function loadFns(f, names, sandbox){
  const { src, ast } = asts[f];
  const parts = [];
  for(const name of names){
    const node = ast.program.body.find(n=>n.type==="FunctionDeclaration" && n.id && n.id.name===name);
    if(!node){ ok("helper "+name+" exists in "+f, false); continue; }
    parts.push(src.slice(node.start, node.end));
  }
  const ctx = vm.createContext({ window:{}, ...(sandbox||{}) });
  try{
    vm.runInContext(parts.join("\n"), ctx);
    return { ctx, fns: vm.runInContext("({"+names.join(",")+"})", ctx) };
  }catch(e){
    ok("helpers "+names.join(", ")+" load from "+f, false, e.message);
    return { ctx, fns: Object.fromEntries(names.map(n=>[n, ()=>undefined])) };
  }
}

/* ── B. new images record the Kinolot compiler label ─────────────────────── */
{
  const sites = [];
  for(const f of FILES){
    const re = /promptCompiler\s*:\s*"([^"]*)"/g; let m;
    while((m = re.exec(asts[f].src))) sites.push([f, m[1]]);
  }
  ok("B every image-generation site in these files writes a compiler label (artroom, lookbook, locations, shots-ui)",
    ["app/artroom.jsx","app/lookbook.jsx","app/locations.jsx","app/shots-ui.jsx"].every(f=>sites.some(s=>s[0]===f)), sites);
  ok("B every label written is \"Kinolot prompt compiler\"", sites.length>=4 && sites.every(s=>s[1]==="Kinolot prompt compiler"), sites);
  const art = asts["app/artroom.jsx"].src;
  ok("B the label is also exported as one constant", /const PROMPT_COMPILER_LABEL = "Kinolot prompt compiler";/.test(art)
    && /window\.PROMPT_COMPILER_LABEL = PROMPT_COMPILER_LABEL;/.test(art));
}

/* ── C. old saved labels display under the product name ──────────────────── */
{
  const { fns:{ promptCompilerLabel } } = loadFns("app/artroom.jsx", ["promptCompilerLabel"]);
  ok("C a saved \"TURN prompt compiler\" displays as \"Kinolot prompt compiler\"", promptCompilerLabel("TURN prompt compiler")==="Kinolot prompt compiler");
  ok("C a new label is shown unchanged", promptCompilerLabel("Kinolot prompt compiler")==="Kinolot prompt compiler");
  ok("C an old product-name label maps too", promptCompilerLabel("Cinema Machine prompt compiler")==="Kinolot prompt compiler");
  ok("C empty / missing labels show nothing", promptCompilerLabel("")==="" && promptCompilerLabel(null)==="" && promptCompilerLabel(undefined)==="");
  ok("C other words are left alone (whole-word match only)", promptCompilerLabel("RETURN compiler")==="RETURN compiler" && promptCompilerLabel("Custom")==="Custom");
  const art = asts["app/artroom.jsx"].src;
  ok("C Image details renders the mapped label, never the raw stored value",
    art.includes('"dt-continuity-mode dt-writing-model"},promptCompilerLabel(meta.promptCompiler))')
      && !art.includes('"dt-continuity-mode dt-writing-model"},meta.promptCompiler)'));
  ok("C the stored value itself is never rewritten (no write-back of the mapped label)",
    !/promptCompiler\s*:\s*promptCompilerLabel\(/.test(art) && !/meta\.promptCompiler\s*=/.test(art));
}

/* ── D. Stage film export name ───────────────────────────────────────────── */
{
  const { fns:{ stageFilmFileName } } = loadFns("app/stage.jsx", ["stageFilmFileName"]);
  const d = "2026-09-28";
  const cases = [
    ["The Matrix", "The_Matrix-2026-09-28.webm"],
    ["", "Kinolot-film-2026-09-28.webm"],
    [null, "Kinolot-film-2026-09-28.webm"],
    ["Untitled film", "Kinolot-film-2026-09-28.webm"],
    ["untitled", "Kinolot-film-2026-09-28.webm"],
    ["  Amélie: Part 2! ", "Amélie_Part_2-2026-09-28.webm"],
    ["???", "Kinolot-film-2026-09-28.webm"],
    ["Blade Runner 2049", "Blade_Runner_2049-2026-09-28.webm"],
    ["Spider-Man / Home", "Spider-Man_Home-2026-09-28.webm"],
    // letters keep their combining marks (review, 2026-09-28): Hindi and Thai words stay whole
    ["\u0928\u092e\u0938\u094d\u0924\u0947 \u0926\u0941\u0928\u093f\u092f\u093e", "\u0928\u092e\u0938\u094d\u0924\u0947_\u0926\u0941\u0928\u093f\u092f\u093e-2026-09-28.webm"],
    ["\u0e2a\u0e27\u0e31\u0e2a\u0e14\u0e35", "\u0e2a\u0e27\u0e31\u0e2a\u0e14\u0e35-2026-09-28.webm"],
  ];
  for(const [t, want] of cases){
    const got = stageFilmFileName(t, d);
    ok("D film export name for "+JSON.stringify(t)+" → "+want, got===want, got);
  }
  const long = String(stageFilmFileName("A".repeat(300), d));
  ok("D a very long title is capped", long.length <= 80+("-"+d+".webm").length && long.endsWith("-"+d+".webm"), long);
  ok("D no name ever uses the codename", !cases.some(([t])=>/TURN/.test(String(stageFilmFileName(t, d)))));
  ok("D without a date it still names today's export", /^Kinolot-film-\d{4}-\d{2}-\d{2}\.webm$/.test(String(stageFilmFileName("", undefined))));
  const st = asts["app/stage.jsx"].src;
  ok("D the Timeline export downloads under that name",
    st.includes("a.download = stageFilmFileName(filmTitle, new Date().toISOString().slice(0,10));") && !st.includes('"TURN-film-"'));
  ok("D the Stage passes the film's title to the Timeline",
    /_stEl\(StageTimelineView,\{ key:"tl", allClips, vids, (?:staleVids, )?imgs, visualSource, selId, onSelectClip,\s*filmTitle:\(project&&project\.title\)\|\|"",/.test(st)
      && /function StageTimelineView\(\{[^}]*\bfilmTitle\b[^}]*\}\)/.test(st));
}

/* ── E. plan display name ────────────────────────────────────────────────── */
{
  const stub = { turnPlanForRes:(r)=> r==="4K" ? "Studio" : r==="1080p" ? "Director" : null };
  const { fns:{ stagePlanName, stagePlanForRes } } = loadFns("app/stage.jsx", ["stagePlanName","stagePlanForRes"], { window:stub });
  ok("E the top plan shows as Producer", stagePlanName("Studio")==="Producer" && stagePlanName("studio")==="Producer");
  ok("E other plan names are unchanged", stagePlanName("Director")==="Director" && stagePlanName("Writer")==="Writer" && stagePlanName("Producer")==="Producer");
  ok("E 4K's lock names the Producer plan; 1080p the Director plan; no plan → null",
    stagePlanForRes("4K")==="Producer" && stagePlanForRes("1080p")==="Director" && stagePlanForRes("720p")===null);
  const st = asts["app/stage.jsx"].src;
  ok("E every Stage plan-lock note goes through the display name",
    !/window\.turnPlanForRes\(r\)\)\|\|"Plan"/.test(st) && /tag:planLocked \? \(stagePlanForRes\(r\)\|\|"Plan"\)\+" plan"/.test(st)
      && /const planResNote = \(r\)=>\{ const p = stagePlanForRes\(r\);/.test(st)
      && st.includes('"Batch takes need the "+stagePlanName("Studio")+" plan — click to upgrade"'));
}

/* ── F. export footers and suggestion chips ──────────────────────────────── */
{
  const bd = asts["app/breakdown.jsx"].src, sh = asts["app/shots-ui.jsx"].src;
  ok("F stripboard + art department bible footers say \"Made with Kinolot\"", (bd.match(/Made with Kinolot<\/div>/g)||[]).length===2);
  ok("F shot list footer says \"Made with Kinolot\"", (sh.match(/Made with Kinolot<\/div>/g)||[]).length===1);
  ok("F the Characters appearance-state chip reads \"Suggested from the script\"",
    asts["app/artroom.jsx"].src.includes('title:"Suggested from the script"},"AI")'));
  const st = asts["app/stage.jsx"].src;
  ok("F Stage's missing-appearance notes no longer name the assistant",
    st.includes('"Suggested from the script; it was never generated. "') && st.includes('" — it was suggested from the script and its sheet has never been generated. "'));
  ok("F the Stage screenplay prompt uses the straight Writers' Room apostrophe",
    asts["app/stage-screenplay-ui.jsx"].src.includes("in the Writers' Room before rendering."));
}

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
