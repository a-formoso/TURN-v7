/*
 * Object keys the Blender relay writes in turn-assets (pure; tested in Node by
 * scripts/test-storage-service-paths.mjs).  Owner decision 2026-09-27: the
 * relay's keys use the same readable top folders as the app,
 *   relay shot PNG   {ownerHandle}--{ownerId}/{slug}--{pid}/shot/{job}/blender-preview-{job}.png
 *   Studio preview   {ownerHandle}--{ownerId}/studio-previews/{slug}--{pid}/{loc}/{preview}.png
 * with the folders from the service-role RPC turn_storage_folders_for (via the
 * adapter's storageFolders), used only when both parse back to exactly the
 * owner and project ids.  Otherwise, and for adapters without storageFolders,
 * the legacy keys {ownerId}/{pid}/shot/… and {ownerId}/studio-previews/{pid}/…
 * are written, as before.  Keys already stored in job state are read as stored.
 * `_internal/…` markers and `blender-studio-internal/…` meshes are unchanged.
 */
import "./storage-keys.js";

const K = globalThis.TurnStorageKeys;

/** {v:1, account, project} → {account, project} when both name exactly these ids. */
export function validStorageFolders(answer, ownerId, projectId) {
  if (!answer || answer.v !== 1 || !K) return null;
  const { account, project } = answer;
  if (!K.isFolderFor(account, ownerId) || !K.isFolderFor(project, projectId)) return null;
  return { account, project };
}

/** The adapter's folders for (owner, project), re-validated; null → legacy keys. */
export async function resolveStorageFolders(adapter, ownerId, projectId) {
  if (!adapter || typeof adapter.storageFolders !== "function") return null;
  try {
    const folders = await adapter.storageFolders(ownerId, projectId);
    return folders ? validStorageFolders({ v: 1, ...folders }, ownerId, projectId) : null;
  } catch (_error) {
    return null;
  }
}

/** The pre-2026-09-27 relay PNG key (every dynamic part generated by the relay). */
export function legacyRelayPngPath(ownerId, projectId, jobId) {
  return `${ownerId}/${projectId}/shot/${jobId}/blender-preview-${jobId}.png`;
}

export function relayPngPathFor(folders, ownerId, projectId, jobId) {
  return folders
    ? `${folders.account}/${folders.project}/shot/${jobId}/blender-preview-${jobId}.png`
    : legacyRelayPngPath(ownerId, projectId, jobId);
}

/** A stored job.pngPath is valid for this owner, project and job in either
    form: exactly the legacy key (which also keeps non-UUID test ids working),
    or five segments whose folders name the owner and the project. */
export function isRelayPngPath(path, ownerId, projectId, jobId) {
  if (typeof path !== "string" || !path) return false;
  if (path === legacyRelayPngPath(ownerId, projectId, jobId)) return true;
  if (!K) return false;
  const seg = path.split("/");
  return seg.length === 5 && K.segmentId(seg[0]) === ownerId && K.segmentId(seg[1]) === projectId &&
    seg[2] === "shot" && seg[3] === jobId && seg[4] === `blender-preview-${jobId}.png`;
}

/** The key a job's completion writes: job.pngTarget, chosen ONCE when the job was
    created (readable folders when available) and kept in the encrypted job state.
    It never depends on a lookup made at completion time, so every attempt of one
    job (a retried device.complete after a lost storage response included) writes
    and adopts exactly the same key and no attempt can leave a second PNG behind.
    A job created before job.pngTarget existed, or holding anything that is not
    this job's own relay key, uses the legacy key, which is just as stable. */
export function relayPngTarget(job, ownerId, projectId) {
  const target = job && typeof job.pngTarget === "string" ? job.pngTarget : "";
  return target && isRelayPngPath(target, ownerId, projectId, job.id)
    ? target : legacyRelayPngPath(ownerId, projectId, job && job.id);
}

/** Studio preview key; `studio-previews` stays folder 2 on purpose, so signed-in
    users still cannot read or delete it directly (only the relay can). */
export function studioPreviewPath(folders, ownerId, projectId, locationId, previewId) {
  const account = folders ? folders.account : ownerId;
  const project = folders ? folders.project : projectId;
  return `${account}/studio-previews/${project}/${locationId}/${previewId}.png`;
}
